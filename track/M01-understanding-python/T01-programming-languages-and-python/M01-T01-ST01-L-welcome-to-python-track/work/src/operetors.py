# Arthimatic operators
print(3 + 3)       # addition
print(3 - 3)       # subtraction
print(3 * 3)       # multiplication
print(3 / 3)       # division
print(3 % 3)       # modulo
print(3 ** 3)      # exponentiation
print(3 // 3)      # floor division

# comparision operators
print(3 == 3)      #True
print(4 != 3)      #True
print(3 < 4)       #True
print(4 > 3)       #True
print(3 >= 3)      #True
print(3 <= 4)      #True

# logical operators
print(True and False)      #False
print(True or False)       #True
print(not True)          #False  

# identity operators
print(3 is 3)          #True
print(3 is not 3)      #False

# membership operators
print(3 in [1,2,3,4,5])    #True
print(3 not in [1,2,3,4,5])  #False