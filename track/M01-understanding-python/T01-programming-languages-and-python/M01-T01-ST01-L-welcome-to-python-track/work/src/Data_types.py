# int 
a = 10
print(type(a),a)

# float
a = 39.64
print(type(a),a)

# bool
a = True
print(type(a),a)

# str
a = "python"
print(type(a),a)

# list
a = [1,2,3,4,5]
print(type(a),a)

# tuple 
a = (10, 20 , 30)
print(type(a),a)

# dict 
a = {1:"hello", 2:"python"}
print(type(a),a)

# set
a = {10,20,30,30,40}
print(type(a),a)

# complex
a = 3+5j
print(type(a),a)

# range
a = range(5)
print(type(a),a)

